 *  '#' 진한 잉크, 'o' 연한 잉크, '.' 빈칸
 */
class Sprite(rows: List<String>) {
    val rows: List<String> = rows
    val width: Int = rows.maxOf { it.length }
    val height: Int = rows.size
}

